import test, { before, after } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID, randomBytes } from 'node:crypto';
import { startFixture, futureDate } from './helpers.js';
import { createPool, transaction } from '../server/db.js';
import { migrate } from '../server/migrate.js';

let fixture, memberId, passwordHash;
before(async () => {
  fixture = await startFixture();
  const result = await fixture.pool.query('SELECT id, password_hash FROM members LIMIT 1');
  memberId = result.rows[0].id;
  passwordHash = result.rows[0].password_hash;
});
after(async () => { if (fixture) await fixture.close(); });

async function addMember({ id = randomUUID(), email = `${randomUUID()}@example.test` } = {}, connection = fixture.pool) {
  const result = await connection.query(`INSERT INTO members(id, name, email, password_hash)
    VALUES ($1, 'SQL Test Member', $2, $3) RETURNING id, email`, [id, email, passwordHash]);
  return result.rows[0];
}

async function addRental({ carId = 'car-bmw', ownerId = memberId,
  start = futureDate(10), end = futureDate(13), rate = 260, status = 'confirmed' } = {}, connection = fixture.pool) {
  const result = await connection.query(`INSERT INTO rentals
    (id, reference, car_id, member_id, start_date, end_date, daily_rate, status,
     car_name, car_image, member_name, member_email, location)
    VALUES ($1,$2,$3,$4,$5,$6,$7,$8,'SQL Test Car','assets/hero.jpg','SQL Test Member','sql@example.test','Tunis')
    RETURNING id, total, daily_rate, start_date::text AS start, end_date::text AS end`,
  [randomUUID(), `DB-${randomBytes(8).toString('hex')}`, carId, ownerId, start, end, rate, status]);
  return result.rows[0];
}

test('migrations can be rerun and reject an altered applied checksum', async () => {
  const previous = await fixture.pool.query('SELECT name, checksum FROM schema_migrations ORDER BY name');
  await migrate(fixture.pool);
  assert.deepEqual((await fixture.pool.query('SELECT name, checksum FROM schema_migrations ORDER BY name')).rows, previous.rows);
  const applied = previous.rows[0];
  await fixture.pool.query('UPDATE schema_migrations SET checksum=$2 WHERE name=$1', [applied.name, 'altered-for-test']);
  try {
    await assert.rejects(migrate(fixture.pool), /changed after application/);
  } finally {
    await fixture.pool.query('UPDATE schema_migrations SET checksum=$2 WHERE name=$1', [applied.name, applied.checksum]);
  }
  await migrate(fixture.pool);
});

test('emails must be lowercase and unique for active members; deleted emails can be reused', async () => {
  const member = await addMember();
  await assert.rejects(addMember({ email: member.email }), { code: '23505' });
  await assert.rejects(addMember({ email: `UPPERCASE-${randomUUID()}@example.test` }), { code: '23514' });
  await fixture.pool.query('UPDATE members SET deleted_at=now(), suspended=true WHERE id=$1', [member.id]);
  const replacement = await addMember({ email: member.email });
  assert.notEqual(replacement.id, member.id);
});

test('invalid car prices, seats, and categories are rejected even without the API', async () => {
  const original = (await fixture.pool.query("SELECT price, seats, category FROM cars WHERE id='car-bmw'")).rows[0];
  for (const price of [0, -1, 100001]) {
    await assert.rejects(fixture.pool.query("UPDATE cars SET price=$1 WHERE id='car-bmw'", [price]), { code: '23514' });
  }
  for (const seats of [0, 10]) {
    await assert.rejects(fixture.pool.query("UPDATE cars SET seats=$1 WHERE id='car-bmw'", [seats]), { code: '23514' });
  }
  await assert.rejects(fixture.pool.query("UPDATE cars SET category='invalid' WHERE id='car-bmw'"), { code: '23514' });
  assert.deepEqual((await fixture.pool.query("SELECT price, seats, category FROM cars WHERE id='car-bmw'")).rows[0], original);
});

test('foreign keys reject missing cars or members and protect rental history from hard deletion', async () => {
  await assert.rejects(addRental({ carId: 'missing-car' }), { code: '23503' });
  await assert.rejects(addRental({ ownerId: randomUUID() }), { code: '23503' });
  const member = await addMember();
  const rental = await addRental({ ownerId: member.id, carId: 'car-audi', start: futureDate(60), end: futureDate(62) });
  await assert.rejects(fixture.pool.query("DELETE FROM cars WHERE id='car-audi'"), { code: '23503' });
  await assert.rejects(fixture.pool.query('DELETE FROM members WHERE id=$1', [member.id]), { code: '23503' });
  assert.equal((await fixture.pool.query('SELECT id FROM rentals WHERE id=$1', [rental.id])).rowCount, 1);
});

test('rental dates and rates are checked and totals are generated by PostgreSQL', async () => {
  await assert.rejects(addRental({ start: futureDate(10), end: futureDate(10) }), { code: '23514' });
  await assert.rejects(addRental({ start: futureDate(10), end: futureDate(9) }), error => ['23514', '22000'].includes(error.code));
  await assert.rejects(addRental({ start: futureDate(10), end: futureDate(376) }), { code: '23514' });
  await assert.rejects(addRental({ start: '2026-02-30' }), { code: '22008' });
  await assert.rejects(addRental({ rate: 0 }), { code: '23514' });
  const rental = await addRental({ rate: 190 });
  assert.equal(rental.total, 570);
  await assert.rejects(fixture.pool.query('UPDATE rentals SET total=1 WHERE id=$1', [rental.id]), { code: '428C9' });
  const updated = await fixture.pool.query('UPDATE rentals SET daily_rate=200 WHERE id=$1 RETURNING total', [rental.id]);
  assert.equal(updated.rows[0].total, 600);
});

test('concurrent direct SQL bookings cannot overlap; adjacent dates and released dates are accepted', async () => {
  const dates = { carId: 'car-porsche', start: futureDate(30), end: futureDate(33) };
  // Dedicated connections guarantee these are separate PostgreSQL transactions.
  const first = await fixture.pool.connect();
  const second = await fixture.pool.connect();
  let results;
  try {
    results = await Promise.allSettled([addRental(dates, first), addRental(dates, second)]);
  } finally { first.release(); second.release(); }
  assert.equal(results.filter(result => result.status === 'fulfilled').length, 1);
  assert.equal(results.find(result => result.status === 'rejected').reason.code, '23P01');
  const winningRental = results.find(result => result.status === 'fulfilled').value;
  const adjacent = await addRental({ ...dates, start: dates.end, end: futureDate(34) });
  assert.ok(adjacent.id);
  await fixture.pool.query("UPDATE rentals SET status='cancelled', cancelled_at=now() WHERE id=$1", [winningRental.id]);
  const replacement = await addRental(dates);
  assert.notEqual(replacement.id, winningRental.id);
});

test('session foreign keys reject missing members and cascade when an unbooked member is deleted', async () => {
  const member = await addMember();
  const token = randomBytes(32).toString('hex');
  const csrf = randomBytes(32).toString('hex');
  await assert.rejects(fixture.pool.query(`INSERT INTO sessions(token_hash,member_id,csrf_token,expires_at)
    VALUES ($1,$2,$3,now()+interval '1 day')`, [token, randomUUID(), csrf]), { code: '23503' });
  await fixture.pool.query(`INSERT INTO sessions(token_hash,member_id,csrf_token,expires_at)
    VALUES ($1,$2,$3,now()+interval '1 day')`, [token, member.id, csrf]);
  await fixture.pool.query('DELETE FROM members WHERE id=$1', [member.id]);
  assert.equal((await fixture.pool.query('SELECT 1 FROM sessions WHERE token_hash=$1', [token])).rowCount, 0);
});

test('a failed transaction rolls back every change, including inserts and price updates', async () => {
  const originalPrice = (await fixture.pool.query("SELECT price FROM cars WHERE id='car-bmw'")).rows[0].price;
  const id = randomUUID();
  await assert.rejects(transaction(fixture.pool, async connection => {
    await connection.query("UPDATE cars SET price=777 WHERE id='car-bmw'");
    await addMember({ id }, connection);
    await connection.query("UPDATE cars SET seats=0 WHERE id='car-bmw'");
  }), { code: '23514' });
  assert.equal((await fixture.pool.query("SELECT price FROM cars WHERE id='car-bmw'")).rows[0].price, originalPrice);
  assert.equal((await fixture.pool.query('SELECT 1 FROM members WHERE id=$1', [id])).rowCount, 0);
});

test('committed records remain available from a fresh connection pool', async () => {
  const member = await addMember();
  const schema = (await fixture.pool.query('SELECT current_schema() AS name')).rows[0].name;
  const reconnected = createPool({ ...fixture.config, schema });
  try {
    const saved = await reconnected.query('SELECT id,email FROM members WHERE id=$1', [member.id]);
    assert.deepEqual(saved.rows[0], member);
  } finally { await reconnected.end(); }
});
